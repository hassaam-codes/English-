// Builds supabase/setup.sql (tables + read-only access + all content) from js/data.js and js/answers.js.
// Usage (from the repo root):  node tools/make-seed.js
// Paste the output file into the Supabase SQL Editor and press Run. It is safe to run more than once:
// existing rows are left alone, so edits made in Supabase are never overwritten.
const fs = require("fs");
const path = require("path");
const { pathToFileURL } = require("url");
const ROOT = path.join(__dirname, "..");
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";

(async () => {
  const d = await import(pathToFileURL(path.join(ROOT, "js/data.js")));
  const { ANSWERS } = await import(pathToFileURL(path.join(ROOT, "js/answers.js")));
  const topicOf = (alt) => (alt.match(/“(.+)”/) || [])[1];
  let sql = `-- English Papers: database setup for Supabase.
-- Paste this whole file into Supabase > SQL Editor > New query, then press Run.
-- Safe to run again: it never overwrites rows you have edited.

-- 1. Tables ---------------------------------------------------------------
create table if not exists public.papers (
  id         text primary key,                 -- e.g. 2024-1  (year - group number)
  year       int  not null,
  grp        text not null check (grp in ('I','II')),
  sort       int  not null,                    -- order on the site
  page       int,                              -- page in the PDF
  alp        boolean not null default false,   -- NEW COURSE (ALP) badge
  title      text not null,
  code       text not null,
  source     text not null,
  alt_question text not null                   -- the English medium "Write TEN sentences" question
);

create table if not exists public.questions (
  id        text primary key,                  -- e.g. 2024-1-q8-0
  paper_id  text not null references public.papers(id) on delete cascade,
  kind      text not null check (kind in ('q8','q9')),
  position  int  not null,                     -- 0 = (i), 1 = (ii) ...
  question  text not null,
  answer    text not null default '',
  unique (paper_id, kind, position)
);

create table if not exists public.repeated (
  id          int generated by default as identity primary key,
  kind        text not null check (kind in ('q8','q9','topics')),
  position    int  not null,
  items       text[] not null,                 -- one sentence, or two when asked in both voices
  times       int  not null,
  appeared_in text not null,
  unique (kind, position)
);

create table if not exists public.site_text (
  key   text primary key,
  value text not null
);

create index if not exists questions_paper_idx on public.questions (paper_id, kind, position);

-- 2. Access: anyone can READ, nobody can change anything through the website ---
alter table public.papers    enable row level security;
alter table public.questions enable row level security;
alter table public.repeated  enable row level security;
alter table public.site_text enable row level security;

do $$
declare t text;
begin
  foreach t in array array['papers','questions','repeated','site_text'] loop
    execute format('drop policy if exists "Public read" on public.%I', t);
    execute format('create policy "Public read" on public.%I for select to anon, authenticated using (true)', t);
    execute format('revoke insert, update, delete, truncate on public.%I from anon, authenticated', t);
    execute format('grant select on public.%I to anon, authenticated', t);
  end loop;
end $$;

-- 3. Content -------------------------------------------------------------
`;
  sql += "insert into public.papers (id, year, grp, sort, page, alp, title, code, source, alt_question) values\n" +
    d.PAPERS.map((p, i) => `  (${q(p.id)}, ${p.year}, ${q(p.group)}, ${i}, ${p.page}, ${!!p.alp}, ${q(p.title)}, ${q(p.code)}, ${q(p.source)}, ${q(p.alt)})`).join(",\n") +
    "\non conflict (id) do nothing;\n\n";

  const rows = [];
  for (const p of d.PAPERS) for (const kind of ["q8", "q9"]) p[kind].forEach((text, i) => {
    if (!ANSWERS[text]) throw new Error("No answer for: " + text);
    rows.push(`  (${q(`${p.id}-${kind}-${i}`)}, ${q(p.id)}, ${q(kind)}, ${i}, ${q(text)}, ${q(ANSWERS[text])})`);
  });
  sql += "insert into public.questions (id, paper_id, kind, position, question, answer) values\n" + rows.join(",\n") + "\non conflict (id) do nothing;\n\n";

  const rep = [];
  for (const [kind, list] of [["q8", d.REPEATED.q8], ["q9", d.REPEATED.q9], ["topics", d.REPEATED.topics]])
    list.forEach((r, i) => rep.push(`  (${q(kind)}, ${i}, array[${r.items.map(q).join(", ")}], ${r.times}, ${q(r.in)})`));
  sql += "insert into public.repeated (kind, position, items, times, appeared_in) values\n" + rep.join(",\n") + "\non conflict (kind, position) do nothing;\n\n";

  const text = {
    cover_title: d.COVER.title, cover_subtitle: d.COVER.subtitle, cover_q8: d.COVER.q8, cover_q9: d.COVER.q9,
    cover_box_heading: d.COVER.boxHeading, cover_box_note: d.COVER.boxNote, cover_footer: d.COVER.footer,
    q8_heading: d.Q8_HEADING, q9_heading: d.Q9_HEADING, alt_heading: d.ALT_HEADING,
    rep_title: d.REPEATED.title, rep_intro: d.REPEATED.intro, rep_q8_title: d.REPEATED.q8Title,
    rep_q9_title: d.REPEATED.q9Title, rep_topic_title: d.REPEATED.topicTitle, rep_note: d.REPEATED.note,
  };
  sql += "insert into public.site_text (key, value) values\n" + Object.entries(text).map(([k, v]) => `  (${q(k)}, ${q(v)})`).join(",\n") + "\non conflict (key) do nothing;\n";

  const out = path.join(ROOT, "supabase", "setup.sql");
  fs.writeFileSync(out, sql);
  console.log("Wrote", out, `(${d.PAPERS.length} papers, ${rows.length} questions, ${rep.length} repeated rows, ${Object.keys(text).length} texts)`);
  void topicOf;
})();
